"""Build results/RESULTS.md from the JSON result files. No number is typed by hand."""

from __future__ import annotations

import json
from pathlib import Path

from .benchmark import RESULTS

BEIR = ("scifact", "nfcorpus", "fiqa")
SYSTEM_LABELS = {
    "bm25_nostem": "BM25, no stemming",
    "bm25": "BM25",
    "dense": "Dense (exact)",
    "dense_hnsw": "Dense (HNSW, ef=64)",
    "hybrid": "Hybrid (RRF)",
    "hybrid_rerank": "Hybrid + cross-encoder",
    "dense_onnx_fp32": "Dense, ONNX fp32",
    "dense_onnx_int8": "Dense, ONNX int8",
    "hybrid_no_date_filter": "Hybrid, no date filter",
}


def _load(name: str) -> dict | None:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _cell(entry: dict | None) -> str:
    if entry is None:
        return "n/a"
    lo, hi = entry["ci95"]
    return f"{entry['mean']:.3f} [{lo:.3f}, {hi:.3f}]"


def _p(value: float) -> str:
    return "<0.001" if value < 0.001 else f"{value:.3f}"


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _verdict(comp: dict) -> str:
    lo, hi = comp["ci95"]
    p = comp.get("p_holm", comp["p"])
    if p < 0.05 and lo > 0:
        return "better"
    if p < 0.05 and hi < 0:
        return "worse"
    return "no clear difference"


def build() -> str:
    out: list[str] = ["# Results", "", "Generated by `local-recall report` from the JSON files in this folder.",
                      "Brackets are 95% bootstrap confidence intervals over queries (10,000 resamples).", ""]
    beir = {name: res for name in BEIR if (res := _load(name))}
    env = _load("environment")

    if beir:
        names = list(beir)
        out += ["## 1. Retrieval quality on BEIR (nDCG@10)", ""]
        header = ["System"] + [f"{n} ({beir[n]['n_queries']} queries, {beir[n]['n_docs']:,} docs)" for n in names]
        order = ["bm25_nostem", "bm25", "dense", "dense_hnsw", "hybrid", "hybrid_rerank"]
        out += [_table(header, [[SYSTEM_LABELS[s]] + [_cell(beir[n]["systems"].get(s, {}).get("ndcg@10")) for n in names] for s in order]), ""]

        out += ["## 2. Recall@100 of the first stage", ""]
        out += [_table(["System"] + names, [[SYSTEM_LABELS[s]] + [_cell(beir[n]["systems"].get(s, {}).get("recall@100")) for n in names] for s in ("bm25", "dense", "hybrid")]), ""]

        out += ["## 3. Paired comparisons (nDCG@10)", "",
                "Difference A minus B on the same queries. p-values come from a paired randomization test",
                "(10,000 permutations) and are Holm-adjusted within each dataset.", ""]
        rows = []
        for n in names:
            for c in beir[n]["comparisons"]:
                rows.append([n, SYSTEM_LABELS[c["a"]], SYSTEM_LABELS[c["b"]], f"{c['diff']:+.3f}",
                             f"[{c['ci95'][0]:+.3f}, {c['ci95'][1]:+.3f}]", _p(c["p_holm"]), _verdict(c)])
        out += [_table(["Dataset", "A", "B", "Difference", "95% CI", "p (Holm)", "Verdict for A"], rows), ""]

        out += ["## 4. Approximate search: HNSW against exact", "",
                "Recall is the overlap with the exact top 10. Latency is one query on the CPU, search only.", ""]
        rows = []
        for n in names:
            exact = beir[n]["latency_cpu"]["dense_search_exact"]
            rows.append([n, "exact", "1.000", f"{beir[n]['systems']['dense']['ndcg@10']['mean']:.3f}", f"{exact['p50_ms']:.2f}", f"{exact['p95_ms']:.2f}"])
            for a in beir[n]["ann_sweep"]:
                rows.append([n, f"HNSW ef={a['ef_search']}", f"{a['recall_vs_exact@10']:.3f}", f"{a['ndcg@10']:.3f}", f"{a['p50_ms']:.2f}", f"{a['p95_ms']:.2f}"])
        out += [_table(["Dataset", "Index", "Recall vs exact @10", "nDCG@10", "p50 ms", "p95 ms"], rows), ""]

        out += ["## 5. Latency per query on the CPU (ms)", ""]
        keys = [("bm25", "BM25 search (top 100)"), ("encode_query_torch_fp32", "Embed query, PyTorch fp32"),
                ("encode_query_onnx_fp32", "Embed query, ONNX fp32"), ("encode_query_onnx_int8", "Embed query, ONNX int8"),
                ("dense_search_exact", "Exact vector search"), ("rerank_top50", "Cross-encoder, 50 candidates")]
        rows = []
        for key, label in keys:
            row = [label]
            for n in names:
                lat = beir[n]["latency_cpu"].get(key)
                row.append(f"{lat['p50_ms']:.1f} / {lat['p95_ms']:.1f}" if lat else "n/a")
            rows.append(row)
        out += [_table(["Step (p50 / p95)"] + names, rows), ""]

        out += ["## 6. Index size and build time", ""]
        rows = []
        for n in names:
            s, b = beir[n]["sizes"], beir[n]["build_seconds"]
            rows.append([n, f"{beir[n]['n_docs']:,}", f"{s['bm25_postings_mb']:.1f}", f"{s['embeddings_mb']:.1f}",
                         f"{s['hnsw_index_mb']:.1f}", f"{b['bm25']:.1f}", f"{b['hnsw']:.1f}"])
        out += [_table(["Dataset", "Docs", "BM25 postings MB", "Embeddings MB", "HNSW index MB", "BM25 build s", "HNSW build s"], rows), ""]

        onnx_sets = [n for n in names if beir[n].get("onnx")]
        if onnx_sets:
            out += ["## 7. On-device model formats", "",
                    "Same embedding model in three formats. Documents and queries are both encoded with the format under test.", ""]
            rows = []
            for n in onnx_sets:
                r = beir[n]
                rows.append([n, "PyTorch fp32", _cell(r["systems"]["dense"]["ndcg@10"]), "n/a",
                             f"{r['latency_cpu']['encode_query_torch_fp32']['p50_ms']:.1f}", "1.0000"])
                for key, label in (("onnx_fp32", "ONNX fp32"), ("onnx_int8", "ONNX int8 (dynamic)")):
                    rows.append([n, label, _cell(r["systems"][f"dense_{key}"]["ndcg@10"]), f"{r['onnx'][key]['model_file_mb']:.1f}",
                                 f"{r['latency_cpu'][f'encode_query_{key}']['p50_ms']:.1f}", f"{r['onnx'][key]['mean_cosine_to_torch_fp32']:.4f}"])
            out += [_table(["Dataset", "Format", "nDCG@10", "Model file MB", "Embed query p50 ms", "Mean cosine to PyTorch fp32"], rows), ""]

    if enron := _load("enron"):
        out += ["## 8. Personal search: questions about one mailbox (Enron)", "",
                f"{enron['n_queries']:,} questions over {enron['n_mailboxes']} mailboxes, {enron['n_docs']:,} emails after de-duplication.",
                f"Each search sees one mailbox up to the question's date: {enron['candidate_pool']['mean']:,.0f} emails on average.", ""]
        metrics = ["recall@1", "recall@5", "recall@10", "mrr@10"]
        order = ["bm25", "dense", "hybrid", "hybrid_rerank", "hybrid_no_date_filter"]
        out += [_table(["System"] + metrics, [[SYSTEM_LABELS[s]] + [_cell(enron["systems"][s][m]) for m in metrics] for s in order]), ""]
        rows = [[SYSTEM_LABELS[c["a"]], SYSTEM_LABELS[c["b"]], f"{c['diff']:+.3f}", f"[{c['ci95'][0]:+.3f}, {c['ci95'][1]:+.3f}]",
                 _p(c["p_holm"]), _verdict(c)] for c in enron["comparisons"]]
        out += ["Paired comparisons on MRR@10:", "", _table(["A", "B", "Difference", "95% CI", "p (Holm)", "Verdict for A"], rows), ""]

    agent_files = sorted(RESULTS.glob("agent*.json"))
    if agent_files:
        out += ["## 9. Agent against single-step retrieval (local language model)", ""]
        for path in agent_files:
            a = json.loads(path.read_text(encoding="utf-8"))
            quant = ", 4-bit" if a.get("load_in_4bit") else ""
            out += [f"Model: `{a['llm']}`{quant}. {a['n_answerable']} answerable questions, {a['n_evidence_removed']} with the evidence removed.", ""]
            s = a["summary"]
            rows = []
            for system, label in (("rag", "Single-step"), ("agent", "Agent (tools, up to 6 steps)")):
                ans, rem = s[f"answerable/{system}"], s[f"evidence_removed/{system}"]
                rows.append([label, _cell(ans["source_hit"]), _cell(ans["answer_f1"]), _cell(ans["abstained"]),
                             _cell(rem["abstained"]), f"{ans['steps']['mean']:.1f}", f"{ans['seconds']['mean']:.1f}"])
            out += [_table(["System", "Cites a gold email", "Answer F1", "Says NOT_FOUND (answerable)",
                            "Says NOT_FOUND (evidence removed)", "Steps", "Seconds"], rows), ""]
            rows = [[c["setting"], c["metric"], f"{c['diff']:+.3f}", f"[{c['ci95'][0]:+.3f}, {c['ci95'][1]:+.3f}]", _p(c["p"])] for c in a["comparisons"]]
            out += ["Agent minus single-step, paired:", "", _table(["Setting", "Metric", "Difference", "95% CI", "p"], rows), ""]

    if env:
        out += ["## Environment", "", "```json", json.dumps(env, indent=2), "```", ""]
    return "\n".join(out)


def main() -> None:
    text = build()
    path: Path = RESULTS / "RESULTS.md"
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path} ({len(text.splitlines())} lines)")
